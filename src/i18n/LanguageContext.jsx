const LanguageContext = createContext({
  language: 'en',
  direction: 'ltr',
  setLanguage: () => {},
  toggleLanguage: () => {},
  t: (_key, fallback, values) => formatValue(fallback || _key, values),
});

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    if (typeof window === 'undefined') return 'en';
    return window.localStorage.getItem(STORAGE_KEY) || 'en';
  });

  const setLanguage = (nextLanguage) => {
    const safeLanguage = nextLanguage === 'ar' ? 'ar' : 'en';
    setLanguageState(safeLanguage);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, safeLanguage);
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  }, [language]);

  const value = useMemo(() => {
    const dictionary = translations[language] || {};
    return {
      language,
      direction: language === 'ar' ? 'rtl' : 'ltr',
      setLanguage,
      toggleLanguage: () => setLanguage(language === 'ar' ? 'en' : 'ar'),
      t: (key, fallback, values) => formatValue(dictionary[key] || fallback || key, values),
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
